// Turns posts/*.md into app/data/posts.generated.ts, newest first.
// Runs in Node at build time, so the Worker ships finished HTML and no Markdown parser.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { marked } from 'marked'
import { parse as parseYaml } from 'yaml'

const root = path.resolve(import.meta.dirname, '..')
const postsDir = path.join(root, 'posts')
const outFile = path.join(root, 'app', 'data', 'posts.generated.ts')

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/

let posts = []
let fileNames = (await readdir(postsDir)).filter((name) => name.endsWith('.md'))

for (let fileName of fileNames) {
  let source = await readFile(path.join(postsDir, fileName), 'utf8')
  let match = FRONTMATTER.exec(source)
  if (!match) throw new Error(`posts/${fileName}: missing frontmatter block`)

  let { title, date } = parseYaml(match[1]) ?? {}
  if (typeof title !== 'string' || title.trim() === '') {
    throw new Error(`posts/${fileName}: frontmatter needs a "title"`)
  }
  if (typeof date !== 'string' || !ISO_DATE.test(date)) {
    throw new Error(`posts/${fileName}: frontmatter needs a "date" like 2026-11-05`)
  }

  posts.push({
    slug: fileName.slice(0, -'.md'.length),
    title,
    date,
    html: await marked.parse(match[2]),
  })
}

posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug))

await writeFile(
  outFile,
  `// Generated by scripts/build-posts.ts from posts/*.md. Do not edit.
import type { Post } from './posts.ts'

export const posts: Post[] = ${JSON.stringify(posts, null, 2)}
`,
)
console.log(`Built ${posts.length} post${posts.length === 1 ? '' : 's'}`)
